// Prioridad: ?lang válido → elección guardada → idioma del navegador
// en primera visita → español para lo no admitido.
export function resolveLang({ query, saved, nav } = {}) {
  const q = String(query ?? '').trim().toLowerCase();
  if (q === 'es' || q === 'en') return q;
  const s = String(saved ?? '').trim().toLowerCase();
  if (s === 'es' || s === 'en') return s;
  const n = String(nav ?? '').trim().toLowerCase();
  if (n.startsWith('en')) return 'en';
  if (n.startsWith('es')) return 'es';
  return 'es';
}

// t(lang, key, vars): texto localizado con {vars} opcionales.
// Si falta la clave en el idioma, cae al español; si falta la clave,
// devuelve la clave (visible, nunca vacío silencioso).
export function t(lang, key, vars) {
  const d = STRINGS[lang] ?? STRINGS.es;
  let s = d[key] ?? STRINGS.es[key] ?? key;
  if (vars && typeof s === 'string') {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return s;
}

export function modalityName(lang, m) {
  if (m === 'donations') return t(lang, 'modalityDonations');
  if (m === 'business') return t(lang, 'modalityBusiness');
  if (m === 'both') return t(lang, 'modalityBoth');
  return t(lang, 'modalityNone');
}

// Aplica textos estáticos: [data-i18n] (texto), [data-i18n-aria]
// (aria-label), [data-i18n-ph] (placeholder), [data-i18n-content]
// (content de meta). Actualiza <html lang> y el estado del selector.
export function applyStatic(lang) {
  const root = document.documentElement;
  root.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(lang, el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(lang, el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(lang, el.dataset.i18nPh));
  });
  document.querySelectorAll('[data-i18n-content]').forEach((el) => {
    el.setAttribute('content', t(lang, el.dataset.i18nContent));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.setAttribute('alt', t(lang, el.dataset.i18nAlt));
  });
  document.querySelectorAll('[data-lang]').forEach((b) => {
    b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
  });
}

export function getInitialLang() {
  const q = new URLSearchParams(location.search).get('lang');
  let saved = '';
  try {
    saved = localStorage.getItem('porque.lang') ?? '';
  } catch { /* sin almacenamiento: se resuelve sin guardar */ }
  const lang = resolveLang({ query: q, saved, nav: navigator.language });
  const ql = String(q ?? '').trim().toLowerCase();
  if (ql === 'es' || ql === 'en') {
    try {
      localStorage.setItem('porque.lang', lang);
    } catch { /* noop */ }
  }
  return lang;
}

// initI18n(onChange): aplica el idioma inicial, cablea el selector y
// devuelve getLang(). Cambiar idioma es en vivo: no recarga (no pierde
// campos), no toca la sesión y no publica. Deja ?lang en la URL para
// que el enlace sea compartible.
export function initI18n(onChange) {
  let lang = getInitialLang();
  applyStatic(lang);
  const setLang = (next) => {
    if (next !== 'es' && next !== 'en') return;
    lang = next;
    try {
      localStorage.setItem('porque.lang', lang);
    } catch { /* noop */ }
    try {
      const url = new URL(location.href);
      url.searchParams.set('lang', lang);
      history.replaceState(null, '', url);
    } catch { /* noop */ }
    applyStatic(lang);
    if (typeof onChange === 'function') onChange(lang);
  };
  document.querySelectorAll('[data-lang]').forEach((b) => {
    b.addEventListener('click', () => setLang(b.dataset.lang));
  });
  return () => lang;
}
